"""
Phase 5 Step 1: Feature consistency check.

Compare feature values stored in the dataset against values generated by
src/features/stage1_features.py for a sample of URLs, for each of the 12
selected Stage-1 features.
"""
import sys, os
sys.path.insert(0, os.getcwd())

import pandas as pd
import numpy as np
import json
from src.features.stage1_features import extract_stage1_features

with open('config/stage1_features.json') as f:
    stage1_cfg = json.load(f)
FEATURES = stage1_cfg['features']

# Load training data (which still has the url column)
df = pd.read_parquet('data/splits/train.parquet')
print(f"Columns available: {list(df.columns)}")
print(f"Rows: {len(df)}")

# Check whether 'url' column survived
if 'url' not in df.columns:
    print("ERROR: 'url' column is missing from the parquet. Cannot do consistency check.")
    sys.exit(1)

# Sample 200 rows across all classes for diversity
sample = df.groupby('dsse_binary_target', group_keys=False).apply(
    lambda g: g.sample(min(100, len(g)), random_state=42)
).reset_index(drop=True)

print(f"Sampled {len(sample)} rows for consistency check")
print()

mismatches = {f: [] for f in FEATURES}
match_counts = {f: 0 for f in FEATURES}

for idx, row in sample.iterrows():
    url = row['url']
    extracted = extract_stage1_features(url)
    
    for feat in FEATURES:
        dataset_val = row[feat]
        extractor_val = extracted[feat]
        
        # Tolerate small float differences for entropy
        if isinstance(extractor_val, float) or isinstance(dataset_val, float):
            if pd.isna(dataset_val) or pd.isna(extractor_val):
                mismatches[feat].append({
                    'url': url[:80],
                    'dataset': str(dataset_val),
                    'extractor': str(extractor_val),
                    'delta': 'NaN'
                })
            elif abs(float(dataset_val) - float(extractor_val)) > 0.01:
                mismatches[feat].append({
                    'url': url[:80],
                    'dataset': str(dataset_val),
                    'extractor': str(extractor_val),
                    'delta': str(abs(float(dataset_val) - float(extractor_val)))
                })
            else:
                match_counts[feat] += 1
        else:
            if int(dataset_val) != int(extractor_val):
                mismatches[feat].append({
                    'url': url[:80],
                    'dataset': str(dataset_val),
                    'extractor': str(extractor_val),
                    'delta': str(abs(int(dataset_val) - int(extractor_val)))
                })
            else:
                match_counts[feat] += 1

# Report
n = len(sample)
print("=" * 70)
print("FEATURE CONSISTENCY REPORT")
print("=" * 70)

all_ok = True
for feat in FEATURES:
    n_mismatch = len(mismatches[feat])
    match_rate = match_counts[feat] / n * 100
    status = "OK" if n_mismatch == 0 else f"MISMATCH ({n_mismatch}/{n})"
    if n_mismatch > 0:
        all_ok = False
    print(f"  {feat:30s}  match={match_rate:5.1f}%  {status}")
    if n_mismatch > 0 and n_mismatch <= 5:
        for m in mismatches[feat]:
            print(f"      url={m['url']}")
            print(f"      dataset={m['dataset']}  extractor={m['extractor']}  delta={m['delta']}")
    elif n_mismatch > 5:
        for m in mismatches[feat][:3]:
            print(f"      url={m['url']}")
            print(f"      dataset={m['dataset']}  extractor={m['extractor']}  delta={m['delta']}")
        print(f"      ... and {n_mismatch - 3} more")

print()
if all_ok:
    print("RESULT: ALL 12 FEATURES ARE CONSISTENT. Safe to proceed with training.")
else:
    print("RESULT: MISMATCHES DETECTED. Must investigate before training.")

# Write report
with open('reports/stage1_feature_consistency.md', 'w') as f:
    f.write("# Stage-1 Feature Consistency Report\n\n")
    f.write(f"Sample size: {n} URLs (100 benign + 100 malicious)\n\n")
    f.write("| Feature | Match Rate | Status |\n")
    f.write("|---------|-----------|--------|\n")
    for feat in FEATURES:
        n_mismatch = len(mismatches[feat])
        match_rate = match_counts[feat] / n * 100
        status = "✅ OK" if n_mismatch == 0 else f"⚠️ MISMATCH ({n_mismatch}/{n})"
        f.write(f"| `{feat}` | {match_rate:.1f}% | {status} |\n")
    f.write("\n")
    
    # Detail mismatches
    for feat in FEATURES:
        if len(mismatches[feat]) > 0:
            f.write(f"\n## Mismatches for `{feat}`\n\n")
            for m in mismatches[feat][:10]:
                f.write(f"- URL: `{m['url']}`\n")
                f.write(f"  - Dataset: {m['dataset']}, Extractor: {m['extractor']}, Delta: {m['delta']}\n")
